def _load(value: Any) -> Dict[str, Any]:
    if isinstance(value, dict):
        return value
    try:
        data = loads(value)
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _table(conn: Any, name: str) -> bool:
    return bool(conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone())


def _delete_version_decisions(data_version: str | None) -> None:
    base.ensure_dual_agent_tables()
    if not data_version:
        return
    with connect() as conn:
        conn.execute("DELETE FROM task_generation_decisions_v15 WHERE data_version = ?", (data_version,))
        conn.commit()


def _load_packages(data_version: str | None) -> List[Dict[str, Any]]:
    if not data_version:
        return []
    base.ensure_dual_agent_tables()
    with connect() as conn:
        if not _table(conn, "product_judgment_packages_v15"):
            return []
        rows = conn.execute("SELECT payload FROM product_judgment_packages_v15 WHERE data_version = ? ORDER BY task_candidate_allowed DESC, created_at ASC", (data_version,)).fetchall()
    packages = [apply_operating_judgment_brief(_load(row["payload"])) for row in rows]
    return [item for item in packages if item.get("taskCandidateAllowed") or item.get("candidateSignal") or item.get("operatingJudgmentBrief")]


def _brief(package: Dict[str, Any]) -> Dict[str, Any]:
    value = package.get("operatingJudgmentBrief")
    return value if isinstance(value, dict) else {}


def _allowed(package: Dict[str, Any]) -> List[str]:
    values = _brief(package).get("allowedActionFamilies") or package.get("allowedActionFamilies") or []
    return [str(item) for item in values if str(item).strip()] if isinstance(values, list) else []


def _forbidden(package: Dict[str, Any]) -> List[str]:
    values = _brief(package).get("forbiddenActionFamilies") or package.get("forbiddenActionFamilies") or []
    return [str(item) for item in values if str(item).strip()] if isinstance(values, list) else []


def _identity(package: Dict[str, Any]) -> Dict[str, Any]:
    product = package.get("productIdentity") if isinstance(package.get("productIdentity"), dict) else {}
    evidence = package.get("fullProductBundleEvidence") if isinstance(package.get("fullProductBundleEvidence"), dict) else {}
    return {"productId": package.get("productId") or product.get("productId"), "storeId": package.get("storeId") or product.get("storeId"), "title": product.get("shortTitle") or product.get("productTitle") or evidence.get("title"), "platform": evidence.get("platform") or product.get("platform"), "verticalCategory": product.get("verticalCategory") or evidence.get("verticalCategory")}


def _creative_plan(package: Dict[str, Any]) -> Dict[str, Any]:
    for value in [package.get("creativeTestPlan"), package.get("agentCreativePack")]:
        if isinstance(value, dict) and isinstance(value.get("groups"), list) and value.get("groups"):
            return value
    return {}


def _valid_creative_groups(plan: Dict[str, Any]) -> List[Dict[str, Any]]:
    groups = plan.get("groups") if isinstance(plan.get("groups"), list) else []
    out: List[Dict[str, Any]] = []
    for group in groups[:5]:
        if not isinstance(group, dict):
            continue
        text = json.dumps(group, ensure_ascii=False)
        if any(marker in text for marker in PLACEHOLDER_MARKERS):
            continue
        if not str(group.get("fullTitle") or "").strip():
            continue
        if not isinstance(group.get("mainImageStructure"), dict):
            continue
        out.append(group)
    return out


def _creative_title_variants(plan: Dict[str, Any]) -> List[Dict[str, Any]]:
    result = []
    for index, group in enumerate(_valid_creative_groups(plan), 1):
        result.append({"groupName": group.get("groupName") or f"{chr(64 + index)}组", "fullTitle": group.get("fullTitle"), "testFocusWords": group.get("testFocusWords") or [], "hypothesis": group.get("hypothesis"), "source": "judgment_agent_creativeTestPlan"})
    return result


def _creative_image_structures(plan: Dict[str, Any]) -> List[Dict[str, Any]]:
    result = []
    for index, group in enumerate(_valid_creative_groups(plan), 1):
        structure = group.get("mainImageStructure") if isinstance(group.get("mainImageStructure"), dict) else {}
        result.append({"groupName": group.get("groupName") or f"{chr(64 + index)}组", "mainImageStructure": structure, "hypothesis": group.get("hypothesis"), "source": "judgment_agent_creativeTestPlan"})
    return result


def _route_candidates(package: Dict[str, Any]) -> List[Dict[str, Any]]:
    brief = _brief(package)
    selected = brief.get("selectedRoute") if isinstance(brief.get("selectedRoute"), dict) else {}
    base_routes = [selected] if selected else []
    base_routes.extend([
        {"routeId": "inventory_capacity_hint", "routeName": "库存只作承接约束", "confidence": 0.2},
        {"routeId": "roas_guard_boundary", "routeName": "ROAS收缩必须有ROI/ROAS恶化证据", "confidence": 0.2},
        {"routeId": "operator_growth_task", "routeName": "运营增长执行路线", "confidence": 0.6},
    ])
    result = []
    seen = set()
    for item in base_routes:
        if not isinstance(item, dict):
            continue
        route_id = str(item.get("routeId") or item.get("id") or "")
        if route_id and route_id not in seen:
            seen.add(route_id)
            result.append({"routeId": route_id, "routeName": item.get("routeName") or item.get("name") or route_id, "confidence": item.get("confidence") or 0.5})
    return result[:4]


