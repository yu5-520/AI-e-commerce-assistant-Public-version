def _field_source(plan: Dict[str, Any]) -> Dict[str, str]:
    value = plan.get("fieldSource")
    if not isinstance(value, dict):
        value = {}
        plan["fieldSource"] = value
    return value


def _mark_source(plan: Dict[str, Any], field: str, source: str) -> None:
    _field_source(plan)[field] = source
    if source == "repair_fallback":
        filled = plan.get("fallbackFilledFields") if isinstance(plan.get("fallbackFilledFields"), list) else []
        if field not in filled:
            filled.append(field)
        plan["fallbackFilledFields"] = filled


def _mark_agent_sources(plan: Dict[str, Any], raw: Dict[str, Any]) -> None:
    for field in AGENT_TEXT_FIELDS:
        if raw.get(field) not in [None, "", [], {}] or plan.get(field) not in [None, "", [], {}]:
            _mark_source(plan, field, "llm_task_mapping_agent")


def _set_if_missing(plan: Dict[str, Any], field: str, fallback: List[Any], source: str = "repair_fallback") -> None:
    if isinstance(plan.get(field), list) and plan.get(field):
        _field_source(plan).setdefault(field, "llm_task_mapping_agent")
        return
    plan[field] = list(fallback)
    _mark_source(plan, field, source)


def _fill_title_image_from_creative_plan(plan: Dict[str, Any], package: Dict[str, Any]) -> None:
    creative = _creative_plan(package)
    titles = _creative_title_variants(creative)
    images = _creative_image_structures(creative)
    if len(titles) >= 2 and len(images) >= 2:
        plan["creativeTestPlan"] = creative
        plan["creativePlanMissing"] = False
        plan["titleVariants"] = titles
        plan["mainImageStructures"] = images
        _mark_source(plan, "creativeTestPlan", "judgment_agent_creativeTestPlan")
        _mark_source(plan, "titleVariants", "judgment_agent_creativeTestPlan")
        _mark_source(plan, "mainImageStructures", "judgment_agent_creativeTestPlan")
        return
    plan["creativePlanMissing"] = True
    plan["titleVariants"] = [{"status": "creative_plan_missing", "reason": "判断Agent未提供2-5组完整标题方案，禁止使用核心场景词/核心卖点模板兜底。"}]
    plan["mainImageStructures"] = [{"status": "creative_plan_missing", "reason": "判断Agent未提供完整主图结构，需重新生成creativeTestPlan。"}]
    _mark_source(plan, "titleVariants", "creative_plan_missing")
    _mark_source(plan, "mainImageStructures", "creative_plan_missing")


